#!/usr/bin/env python3
"""Data validation for NutriOpt-Bench datasets and targets."""
from __future__ import annotations

import json
import os
from pathlib import Path

import numpy as np
import pandas as pd


def validate_nhanes(path="data/nhanes.csv"):
    df = pd.read_csv(path, low_memory=False, na_values=["", " ", "NA"])
    nuts = [c for c in df.columns if c not in ("food_id", "grams")]
    report = {
        "file": path,
        "n_rows": len(df),
        "n_unique_food_id": int(df["food_id"].nunique()),
        "duplicate_food_id_rows": int(df["food_id"].duplicated().sum()),
        "nan_rate": df[nuts].isnull().mean().to_dict(),
        "inf_count": int(np.isinf(np.nan_to_num(df[nuts].to_numpy(dtype=float), nan=0.0)).sum()),
        "negative_nutrient_cells": int((df[nuts].fillna(0) < 0).sum().sum()),
        "zero_rows": int((df[nuts].fillna(0).sum(axis=1) == 0).sum()),
        "grams_min": float(df["grams"].min()),
        "grams_max": float(df["grams"].max()),
    }
    return report


def validate_targets(path="data/target.csv"):
    df = pd.read_csv(path)
    bad = 0
    dims = []
    impossible = 0
    for i in range(len(df)):
        try:
            td = eval(df.iloc[i, 0])
        except Exception:
            bad += 1
            continue
        dims.append(len(td))
        for k, (lo, hi) in td.items():
            if lo > hi:
                impossible += 1
            if not np.isfinite(lo) or not np.isfinite(hi):
                impossible += 1
    return {
        "file": path,
        "n": len(df),
        "parse_failures": bad,
        "dim_min": int(min(dims)) if dims else None,
        "dim_max": int(max(dims)) if dims else None,
        "dim_mean": float(np.mean(dims)) if dims else None,
        "impossible_bound_pairs": impossible,
    }


def main():
    os.makedirs("docs", exist_ok=True)
    os.makedirs("results/reproducibility", exist_ok=True)
    reports = {
        "nhanes": validate_nhanes(),
        "targets": validate_targets(),
        "food_type_rows": len(pd.read_csv("data/food_type.csv")),
        "representative_12": len(pd.read_csv("data/representative_targets.csv")),
        "representative_45": len(pd.read_csv("data/representative_targets_45.csv")),
        "representative_100": len(pd.read_csv("data/representative_targets_100.csv")),
    }
    # recipe
    fd = pd.read_csv("data/food_data.csv")
    reports["food_data"] = {"n": len(fd), "cols": list(fd.columns)}
    with open("data/allrecipes.json") as f:
        ar = json.load(f)
    reports["allrecipes_json"] = {"n": len(ar)}

    out_json = "results/reproducibility/data_validation.json"
    with open(out_json, "w") as f:
        json.dump(reports, f, indent=2)

    md = ["# DATA_VALIDATION.md", "", "Generated by `validate_data.py`.", ""]
    md.append("## NHANES")
    for k, v in reports["nhanes"].items():
        md.append(f"- **{k}**: `{v}`")
    md.append("")
    md.append("## Targets")
    for k, v in reports["targets"].items():
        md.append(f"- **{k}**: `{v}`")
    md.append("")
    md.append("## Notes")
    md.append("- Duplicate `food_id` rows are treated as distinct selectable instances (different grams).")
    md.append("- `vitamin_d` has substantial missingness; filled with 0 after load if retained.")
    md.append("- Units are not normalized in code; interpret nutrient scales consistently within a dataset.")
    md.append("- Intrinsically infeasible targets must be flagged via MILP/bounding before attributing algorithm failure.")
    Path("docs/DATA_VALIDATION.md").write_text("\n".join(md))
    print("Wrote", out_json, "and docs/DATA_VALIDATION.md")


if __name__ == "__main__":
    main()
